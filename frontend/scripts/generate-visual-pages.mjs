// Run before next dev/build so newly added app routes appear in the visual editor.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const items = [];
const labels = {
  '/': 'Home', '/faq': 'Frequently asked questions',
  '/biodata': 'Find biodata', '/guidelines': 'Guidelines',
  '/pricing': 'Pricing', '/premium': 'Premium membership',
  '/contact': 'Contact', '/about': 'About us',
};
function scan(directory, segments = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (entry.name.startsWith('_') || entry.name === 'api') continue;
      scan(path.join(directory, entry.name),
        entry.name.startsWith('(') && entry.name.endsWith(')')
          ? segments : [...segments, entry.name]);
    } else if (entry.name === 'page.tsx' || entry.name === 'page.jsx' ||
               entry.name === 'page.js' || entry.name === 'page.ts') {
      const route = '/' + segments.join('/');
      const name = labels[route] || segments.map(part =>
        part.startsWith('[') ? 'Dynamic page' : part.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase())
      ).join(' / ') || 'Home';
      items.push({ path: route, label: name, dynamic: route.includes('[') });
    }
  }
}
scan(path.join(root, 'app'));
items.sort((a, b) => a.path.localeCompare(b.path));
const output = '// Generated by scripts/generate-visual-pages.mjs. Do not edit manually.\n' +
  'export const visualPageCatalog: ReadonlyArray<{ path: string; label: string; dynamic: boolean }> = ' +
  JSON.stringify(items, null, 2) + ';\n';
writeFileSync(path.join(root, 'lib', 'visual-page-catalog.ts'), output);
console.log('Generated visual editor catalogue for', items.length, 'page routes.');
